CREATE TABLE IF NOT EXISTS mkt2_service_rates (
  serviceType VARCHAR(80) NOT NULL PRIMARY KEY,
  description VARCHAR(180) NOT NULL DEFAULT '',
  baseAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
  extraPersonAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
  createdAt DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  syncStatus VARCHAR(20) NOT NULL DEFAULT 'pending',
  syncedAt DATETIME NULL,
  source VARCHAR(40) NOT NULL DEFAULT 'hostinger',
  branchCode VARCHAR(50) NOT NULL DEFAULT '28'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mkt2_hotels (
  hotelName VARCHAR(200) NOT NULL,
  hotelNormalized VARCHAR(200) NOT NULL PRIMARY KEY,
  active TINYINT(1) NOT NULL DEFAULT 1,
  source VARCHAR(80) NOT NULL DEFAULT '',
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

DROP PROCEDURE IF EXISTS add_column_if_missing;
DELIMITER $$
CREATE PROCEDURE add_column_if_missing(IN p_table VARCHAR(64), IN p_column VARCHAR(64), IN p_sql TEXT)
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = p_table
      AND COLUMN_NAME = p_column
  ) THEN
    SET @ddl = p_sql;
    PREPARE stmt FROM @ddl;
    EXECUTE stmt;
    DEALLOCATE PREPARE stmt;
  END IF;
END$$
DELIMITER ;

CALL add_column_if_missing('mkt2_service_rates','description','ALTER TABLE mkt2_service_rates ADD COLUMN description VARCHAR(180) NOT NULL DEFAULT ''''');
